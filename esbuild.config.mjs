/**
 * Development and production bundling for the Commitment plugin.
 */

import esbuild from "esbuild";

// Recognize the production invocation mode.
const production = process.argv[2] === "production";

// Compose the shared build options.
const options = {
    banner: {
        js: "/* THIS IS A GENERATED/BUNDLED FILE BY ESBUILD */",
    },
    entryPoints: ["src/main.ts"],
    bundle: true,
    external: ["obsidian"],
    format: "cjs",
    target: "es2021",
    logLevel: "info",
    sourcemap: production ? false : "inline",
    treeShaking: true,
    outfile: "main.js",
    minify: production,
    platform: "browser",
    mainFields: ["browser", "module", "main"],
};

// Create the build context.
const context = await esbuild.context(options);

// Build once for production and keep watching during development.
if (production) {
    // Rebuild the production bundle once.
    await context.rebuild();

    // Release the build context.
    await context.dispose();
} else {
    // Watch the sources for development rebuilds.
    await context.watch();
}
